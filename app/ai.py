    async def daily_summary(self, transcript: str, group_name: str, day: str) -> str:
        try:
            resp = await self.client.messages.create(
                model=self.model_summary,
                max_tokens=3000,
                system=SUMMARY_SYSTEM.format(target=self.target),
                messages=[{
                    "role": "user",
                    "content": (
                        f"Чат: {group_name or 'родительский чат'}\n"
                        f"Дата: {day}\n\n"
                        f"Сообщения за день (время, автор, перевод):\n\n{transcript}"
                    ),
                }],
            )
            return _first_text(resp).strip()
        except Exception as exc:  # noqa: BLE001
            log.error("Ошибка построения сводки: %s", exc)
            return "⚠️ Не удалось построить сводку — ошибка обращения к Claude API. Сообщения сохранены."

    async def history_query(self, kind: str, transcript: str, today: str,
                            tomorrow: str, question: str = "") -> str:
        """Ответ на вопрос по всей накопленной истории чата.

        kind: events | todo | money | ask
        """
        systems = {
            "events": EVENTS_SYSTEM,
            "todo": TODO_SYSTEM,
            "money": MONEY_SYSTEM,
            "ask": ASK_SYSTEM,
        }
        if kind not in systems:
            raise ValueError(f"Неизвестный тип запроса: {kind}")

        user = f"Переписка (дата, время, автор, перевод):\n\n{transcript}"
        if kind == "ask":
            user = f"Вопрос родителя: {question}\n\n{user}"

        try:
            resp = await self.client.messages.create(
                model=self.model_summary,
                max_tokens=3000,
                system=systems[kind].format(
                    target=self.target, today=today, tomorrow=tomorrow
                ),
                messages=[{"role": "user", "content": user}],
            )
            return _first_text(resp).strip()
        except Exception as exc:  # noqa: BLE001
            log.error("Ошибка запроса к истории (%s): %s", kind, exc)
            return "⚠️ Не удалось обработать запрос — ошибка обращения к Claude API."

